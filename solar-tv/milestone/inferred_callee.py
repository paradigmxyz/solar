"""The ranking certificate of a loop inside an internal function, from solar-verify's inference.

inferred.py binds a loop's inferred invariant on an entry function. A loop inside an internal
function (Uniswap v2-core's Math.sqrt, called from several places) runs under its caller's return
record, so its certificate is stated for every caller:

- the cut points are the loop's header, read off the blocks that enter it (each must enter only
  the header), and every frame resumed after a return;
- the invariant is the frame at the header under any caller's return record, entered from one of
  the header's predecessors; it keeps no data: termination needs only the guard, which every
  segment proof reads off the code;
- the measure solar-verify proved, which must be one of the guard's two variables (a 'while (a < b)'
  loop), becomes 'rank': that variable's header phi, read through its input from the predecessor,
  in Nat.

Nothing here is trusted: the segment proofs check that the rank falls on every back edge.

Usage: inferred_callee.py STAGE0 SOL INFERRED FUNCTION OUT NAMESPACE MODULE

INFERRED is what 'solar-verify --show-inferred --infer-bound-measures SOL' prints: the flag lets
inference try a guard's bound alone as the measure, which Newton's iteration needs.
"""

import hashlib
import os
import re
import sys

from cutpoints import Unsupported, mir_headers, parse_mir
from inferred import definitions, inferred_clauses, reach


def generate(stage0_text, sol, inferred_text, function, stage0_name, namespace, module):
    funcs = parse_mir(stage0_text)
    fidx = next((i for i, f in enumerate(funcs) if f["name"] == function), None)
    if fidx is None:
        raise Unsupported(f"no MIR function @{function}")
    blocks = funcs[fidx]["blocks"]
    heads, preds, succ = mir_headers(funcs[fidx])
    if len(heads) != 1:
        raise Unsupported(f"@{function}: {len(heads)} loop headers, one supported")
    (h,) = heads
    for p in preds[h]:
        if succ[p] != [h]:
            raise Unsupported(f"@{function} bb{p}: enters bb{h} and other blocks")
    _, measure, line = inferred_clauses(inferred_text, function)
    m = re.search(rf"function {function}\b.*?while \((\w+) < (\w+)\)", sol, re.S)
    if not m:
        raise Unsupported(f"{function}: no 'while (a < b)' loop in the source")
    lo, hi = m[1], m[2]
    if measure not in (lo, hi):
        raise Unsupported(f"{function}: measure {measure} is not a variable of the guard")
    defs = definitions(funcs[fidx])
    hphis, _, hterm = blocks[h]
    phi_in = {d: dict(inc) for d, inc in hphis}
    bm = re.fullmatch(r"\.branch \(\.value (\d+)\) (\d+) (\d+)", hterm)
    gdef = defs.get(int(bm[1])) if bm else None
    if not gdef or gdef[:2] != ("pure", "lt"):
        raise Unsupported(f"@{function} bb{h}: the header does not branch on 'lt'")
    a, b = gdef[2]
    if not (a.startswith(".value") and b.startswith(".value")):
        raise Unsupported(f"@{function} bb{h}: the guard does not compare two values")
    phis = {lo: int(a.split()[1]), hi: int(b.split()[1])}
    if any(v not in phi_in for v in phis.values()):
        raise Unsupported(f"@{function} bb{h}: the guard does not compare header phis")
    loop = reach(h, lambda n: succ[n]) & reach(
        h, lambda n: [x for x in blocks if n in succ[x]]
    ) | {h}
    if int(bm[2]) not in loop:
        raise Unsupported(f"@{function} bb{h}: the guard's true branch leaves the loop")
    mphi = phis[measure]

    def read(op):
        kind, n = op.split()
        return f"({n} : EvmRules.Word).toNat" if kind == ".const" else f"(env {n}).toNat"

    sha = lambda t: hashlib.sha256(t.encode()).hexdigest()
    ps = sorted(preds[h])
    out = [
        "-- Generated by solar-tv/milestone/inferred_callee.py from what solar-verify --show-inferred printed",
        f"-- (sha256 {sha(inferred_text)}) and {stage0_name} (sha256 {sha(stage0_text)}); do not edit.",
        "import SolarTV.MIR.Program",
        f"import {module}",
        "",
        "/-!",
        f"# The ranking certificate of `{function}`'s loop, under any caller",
        "",
        f"solar-verify proved, for the loop at line {line} of the source (`while ({lo} < {hi})`), the",
        f"termination measure `{measure}`. It is bound to phi {mphi} of bb{h} of function {fidx} of the first",
        f"lowered MIR (the guard compares phi {phis[lo]} with phi {phis[hi]}), read through its input from",
        f"each predecessor ({', '.join(f'bb{p}' for p in ps)}). The cut points are the header and every",
        "frame resumed after a return; the invariant is the frame at the header under any caller's",
        "return record. The segment proofs check that the rank falls on every back edge.",
        "-/",
        "",
        f"namespace {namespace}",
        "",
        "open SolarTV Machine",
        "",
        "/-- Cut points: the header, read off the blocks that enter it, and every resumed frame. -/",
        "def cut : MIR.Lowered.Frame → Bool := fun x =>",
        "  match x.2.1 with",
        f"  | .enter f p _ => (f == {fidx} && ({' || '.join(f'p == {p}' for p in ps)}))",
        "  | .resume .. => true",
        "",
        "/-- The header, entered from one of its predecessors, under the caller's return. -/",
        "def Inv (r : MIR.Lowered.Return) (stack : List MIR.Lowered.Return) (x : MIR.Lowered.Frame) : Prop :=",
        f"  ∃ p env s, x = (r :: stack, .enter {fidx} p {h}, env, s) ∧ ({' ∨ '.join(f'p = {p}' for p in ps)})",
        "",
        "/-- The caller resumed after the function's `leave`. -/",
        "def Back (r : MIR.Lowered.Return) (stack : List MIR.Lowered.Return) (x : MIR.Lowered.Frame) : Prop :=",
        "  ∃ env s, x = (stack, .resume r.fn r.block r.rest r.term, env, s)",
        "",
        f"/-- The measure `{measure}` at the header, in Nat. -/",
        "def rank : MIR.Lowered.Frame → Nat",
    ]
    for p in ps:
        r = read(phi_in[mphi][p])
        out.append(f"  | (_, .enter _ {p} _, {'env' if 'env ' in r else '_'}, _) => {r}")
    out += ["  | _ => 0", "", f"end {namespace}", ""]
    return "\n".join(out)


def main():
    stage0, sol, inferred, function, out_path, namespace, module = sys.argv[1:8]
    texts = []
    for path in (stage0, sol, inferred):
        with open(path) as f:
            texts.append(f.read())
    text = generate(*texts, function, os.path.basename(stage0), namespace, module)
    with open(out_path, "w") as f:
        f.write(text)


if __name__ == "__main__":
    try:
        main()
    except Unsupported as e:
        sys.exit(f"inferred_callee.py: unsupported: {e}")
