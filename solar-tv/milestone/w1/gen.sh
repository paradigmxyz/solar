#!/usr/bin/env bash
# Exports the stages of w1's compilation as Lean and checks them.
#
# Builds solar, compiles w1.sol with the pinned options, writes every stage into gen/ with
# -Zemit-lean-stages, checks that the exported bytecode is the compiler's --emit=bin-runtime
# output with and without the flag, that the manifest's hashes match the files, and builds the
# stages and their checks with lake. Set W1_SKIP_BUILD=1 to use an existing build, and SOLAR to
# pick the binary.
set -euo pipefail

here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
root="$(cd "$here/../../.." && pwd)"
cd "$root"

source=solar-tv/milestone/w1/w1.sol
gen=solar-tv/milestone/w1/gen
options=(-Ogas --evm-version osaka --emit=bin-runtime)
# The runtime bytecode the milestone pins.
expected=34602e575f3560e01c806313d1aa2e03602e5760443610602e5760043560243581019081106032575f5260205ff35b5f5ffd5b6011602052634e487b715f526024601cfd

target="${CARGO_TARGET_DIR:-$root/target}"
if [[ -z "${W1_SKIP_BUILD:-}" ]]; then
    cargo build ${CARGO_BUILD_JOBS:+-j "$CARGO_BUILD_JOBS"} --bin solar
fi
solar="${SOLAR:-$target/debug/solar}"

bin_runtime() {
    python3 -c 'import json, sys; c = json.load(sys.stdin)["contracts"]; print(c[sys.argv[1]]["bin-runtime"])' \
        "$source:Main"
}
compile() {
    "$solar" "$source" "${options[@]}" "$@" 2>/dev/null
}

# The commit in the compiler's version names the sources it was built from: they must be the
# checkout's, which must have no uncommitted compiler changes.
version="$(compile | python3 -c 'import json, sys; print(json.load(sys.stdin)["version"])')"
commit="$(sed -n 's/.*+commit\.\([0-9a-f]\{8\}\).*/\1/p' <<<"$version")"
if [[ -z "$commit" ]]; then
    echo "error: cannot read the compiler commit from its version $version" >&2
    exit 1
fi
if ! git diff --quiet HEAD -- crates Cargo.toml Cargo.lock; then
    echo "error: the compiler sources have uncommitted changes" >&2
    exit 1
fi
if ! git diff --quiet "$commit" HEAD -- crates Cargo.toml Cargo.lock; then
    echo "error: the compiler reports commit $commit, whose sources differ from HEAD;" >&2
    echo "       rebuild it (touch crates/config/build.rs) so that its version is current" >&2
    exit 1
fi

plain="$(compile | bin_runtime)"
exported="$(compile "-Zemit-lean-stages=$gen" | bin_runtime)"
if [[ "$plain" != "$exported" ]]; then
    echo "error: -Zemit-lean-stages changed the bytecode" >&2
    exit 1
fi
if [[ "$plain" != "$expected" ]]; then
    echo "error: the bytecode is not the milestone's:" >&2
    echo "  $plain" >&2
    exit 1
fi

# The manifest binds the stages to the source, the compiler and the bytecode.
python3 - "$gen/Main" "$source" "$plain" <<'EOF'
import hashlib, json, pathlib, sys

directory, source, bytecode = pathlib.Path(sys.argv[1]), sys.argv[2], sys.argv[3]
manifest = json.loads((directory / "manifest.json").read_text())
sha = lambda path: hashlib.sha256(pathlib.Path(path).read_bytes()).hexdigest()
assert [s["path"] for s in manifest["sources"]] == [source], manifest["sources"]
assert manifest["sources"][0]["sha256"] == sha(source), "source hash"
assert manifest["bytecode"] == bytecode, "manifest bytecode"
assert manifest["bytecode_sha256"] == hashlib.sha256(bytes.fromhex(bytecode)).hexdigest()
for stage in manifest["stages"]:
    assert stage["sha256"] == sha(directory / stage["file"]), stage["file"]
# The stages lake builds, in the manifest's order.
imports = "".join(f"import gen.Main.{s['file'][:-5]}\n" for s in manifest["stages"])
(directory.parent / "Stages.lean").write_text(
    "-- Generated by gen.sh from Main/manifest.json; do not edit.\n"
    + imports + "import gen.Main.Manifest\n")
print("stages:", ", ".join(f"{s['definition']} ({s['pass']})" for s in manifest["stages"]))
EOF

(cd solar-tv && lake build SolarTV W1)
echo "w1: $version, bytecode $plain"

