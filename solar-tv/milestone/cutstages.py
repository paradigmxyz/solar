#!/usr/bin/env python3
"""Writes the cut-point proofs of a certified contract's EVM IR stages, for every call.

certify.py proves each stage by running both programs to their ends, which a program whose
loops run as many times as its calldata says cannot do on every call; certify.sh --exclude then
leaves such functions out. This proves the EVM IR stages, from the scheduled EVM IR to the final
one, through cut points instead (cutpoints.py picks them and the relation, SolarTV.CutPoint lifts
the segments to whole runs), on every call, excluded functions included.

    cutstages.py GEN_DIR --gen-module M --proof-dir D --proof-module P --namespace N

It writes D/Loops/<Stage>.lean, one module per pair of consecutive EVM IR stages, and
D/Loops.lean, which chains them into a stage from the scheduled EVM IR to the final EVM IR on
every call (¤anyCall¤). A pair cutpoints.py cannot relate stops it with the reason, naming the
pass. The MIR stages and stack scheduling are not covered.
"""

import argparse
import itertools
import json
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import cutpoints

AXIOMS = "[propext, Classical.choice, Quot.sound]"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("gen", type=pathlib.Path)
    ap.add_argument("--gen-module", required=True)
    ap.add_argument("--proof-dir", required=True, type=pathlib.Path)
    ap.add_argument("--proof-module", required=True)
    ap.add_argument("--namespace", required=True)
    ap.add_argument("--heartbeats", type=int, default=8000000)
    ap.add_argument("--only", help="write only this stage's module")
    args = ap.parse_args()
    manifest = json.loads((args.gen / "manifest.json").read_text())
    exported = f"SolarTV.Export.{manifest['contract']}"
    stages = [
        {
            "def": s["definition"],
            "module": s["file"][: -len(".lean")],
            "pass": s["pass"],
            "blocks": cutpoints.parse_evm((args.gen / s["file"]).read_text()),
        }
        for s in manifest["stages"]
        if s["kind"] in ("sched", "evm")
    ]
    out = args.proof_dir / "Loops"
    out.mkdir(parents=True, exist_ok=True)
    ns, gm, pm = args.namespace, args.gen_module, args.proof_module
    opens = f"EvmRules SolarTV.CutPoint Machine {exported} SolarTV.Milestone.W1"
    names = []
    for a, b in itertools.pairwise(stages):
        try:
            cuts = cutpoints.evm_cuts(b["pass"], a["blocks"], b["blocks"])
        except cutpoints.Unsupported as e:
            raise SystemExit(f"error: {b['def']}: {e}")
        names.append(b)
        if args.only and args.only != b["def"]:
            continue
        body = cutpoints.evm_pair(
            a, b, cuts, len(a["blocks"]) + 1, len(b["blocks"]) + 1, args.heartbeats
        )
        p = b["def"]
        text = (
            "-- Generated by solar-tv/milestone/cutstages.py; do not edit.\n"
            "import W1Proofs.Segment\nimport W1Proofs.Stage\nimport W1Proofs.Axioms\nimport SolarTV.Composition\n"
            f"import {gm}.{a['module']}\nimport {gm}.{b['module']}\n\n"
            f"/-! ¤{b['pass']}¤ ({a['def']} to {p}) on every call, through the cut points "
            + ", ".join(
                f"block {ia} of {a['def']} and {ib} of {p} at {h} words"
                for ia, ib, h in cuts
            )
            + ". -/\n\n"
            f"namespace {ns}\n\nopen {opens}\n\n"
            + body
            + f"/-- ¤{b['pass']}¤ on every call. -/\n"
            f"theorem stage_{p}_all (o : Oracle) : Stage (evmirSem o) (evmirSem o) {a['def']} {p} anyCall :=\n"
            f"  stage_of_certified ({p}_sim o).certified\n\n"
            f"/-- info: '{ns}.stage_{p}_all' depends on axioms: {AXIOMS} -/\n"
            f"#guard_msgs in\n#print axioms stage_{p}_all\n\n"
            f"end {ns}\n"
        )
        (out / f"{b['module']}.lean").write_text(text.replace(chr(164), chr(96)))
    first, last = stages[0], stages[-1]
    steps = "⟨" + ", ".join(f"stage_{b['def']}_all o" for b in names) + ", trivial⟩"
    root = (
        "-- Generated by solar-tv/milestone/cutstages.py; do not edit.\n"
        + "".join(f"import {pm}.Loops.{b['module']}\n" for b in names)
        + "import SolarTV.Composition\n\n"
        f"/-! The EVM IR stages of ¤{manifest['contract']}¤ from the scheduled EVM IR "
        f"¤{first['def']}¤ to the final ¤{last['def']}¤, each through cut points, chained on "
        "every call. -/\n\n"
        f"namespace {ns}\n\nopen {opens}\n\n"
        f"/-- Every EVM IR stage, chained, on every call under every oracle. -/\n"
        f"theorem evmir_stages_all (o : Oracle) :\n"
        f"    Stage (evmirSem o) (evmirSem o) {first['def']} {last['def']} anyCall :=\n"
        f"  Steps.stage (S := evmirSem o) {first['def']} [{', '.join(b['def'] for b in names)}] {steps}\n\n"
        f"/-- info: '{ns}.evmir_stages_all' depends on axioms: {AXIOMS} -/\n"
        f"#guard_msgs in\n#print axioms evmir_stages_all\n\nend {ns}\n"
    )
    (args.proof_dir / "Loops.lean").write_text(root.replace(chr(164), chr(96)))
    print(json.dumps({"stages": [b["def"] for b in names]}))


if __name__ == "__main__":
    main()
