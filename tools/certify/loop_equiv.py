#!/usr/bin/env python3
"""Emit a cut-point certificate for a loop-carrying function's lowered MIR.

Reads the loop-head manifest that solar-verify writes (`--emit-loop-heads`) and the lowered MIR
module that solar exports (`-Zemit-lean-stages`, the `Stage0.lean` of the contract), and writes a
Lean module defining a `Verify.LoopSource.Equiv.Cut` for the function's loop: its header block, the
template of the frame at the header and the cases the iteration runs under. The certificate is a
claim only: `Cut.check` in solidity-lean re-runs the MIR and rejects it unless every arrival at the
header matches the template, so a wrong certificate fails there, never silently.

Rules, all read off the MIR and the manifest, none off a file name or a hash:

* the header is the one block of the function with a phi arm from a block it reaches (a back
  edge); a function whose manifest lists other than one loop is refused;
* every value the header's phis, the loop's blocks or the blocks before the header bind is a
  template value; a `calldataload` of argument word `i` and an `sload` of a constant slot that
  nothing before the header stores are fixed words (`arg i`, `init k`); every other value is a
  header word, and a value or memory word that an `assume ... eq` in the loop pins to another
  shares its header word;
* values the module's entry function binds and the loop function does not rebind are the word 0
  after the tail call into it;
* memory words at constant offsets that the loop or the blocks before the header write are header
  words; a storage write before the header or in the loop is refused (the template has none);
* the cases are: every `assume` the loop makes on a header comparison holds, or the header's
  branch leaves the loop.

Usage: loop_equiv.py MANIFEST STAGE0 FUNCTION SELECTOR NARGS OUT
"""

import json
import re
import sys
from typing import NoReturn

HEADER = """import Verify.LoopSource.Equiv.Cut

/-! Generated by `tools/certify/loop_equiv.py` for `{fname}` (selector {sel:#010x}); do not edit. -/

namespace Verify.LoopSource.Equiv.Generated
open SolidCore.Refinement.Generic Verify.LoopSource.Equiv

/-- The cut-point certificate of `{fname}`'s loop. -/
def cut : Cut :=
  {{ fn := {fn}, head := {head},
    ids := [
      {ids}],
    mem := [{mems}], writes := [], nhw := {nhw},
    cases := [{cases}],
    fuel := {fuel} }}

end Verify.LoopSource.Equiv.Generated
"""


def die(msg: str) -> NoReturn:
    sys.stderr.write("loop_equiv: " + msg + "\n")
    sys.exit(2)


def parse_module(text):
    m = re.search(r"\{ entry := (\d+),", text)
    if not m:
        die("no module entry")
    entry = int(m.group(1))
    names = re.findall(r"^    -- @(\w+)", text, re.MULTILINE)
    parts = re.split(r"^    -- @\w+.*$", text, flags=re.MULTILINE)[1:]
    funcs = []
    for name, body in zip(names, parts):
        blocks = []
        for bm in re.finditer(
            r"-- bb(\d+)\n\s*⟨(.*?),\n\s*\[(.*?)\],\n\s*(\.(?:branch|jump|switch|tailCall|ret|revert|stop|invalid|leave)[^⟩]*)⟩",
            body,
            re.DOTALL,
        ):
            phis = [
                (
                    int(d),
                    [
                        (int(p), a)
                        for p, a in re.findall(
                            r"\((\d+), (\.const \w+|\.value \d+)\)", arms
                        )
                    ],
                )
                for d, arms in re.findall(r"\((\d+), \[(.*?)\]\)", bm.group(2))
            ]
            insts = (
                [i.strip() for i in re.split(r",\n", bm.group(3)) if i.strip()]
                if bm.group(3).strip()
                else []
            )
            blocks.append({"phis": phis, "insts": insts, "term": bm.group(4).strip()})
        pm = re.search(r"params := \[([\d, ]*)\]", body)
        params = [int(x) for x in pm.group(1).split(",") if x.strip()] if pm else []
        funcs.append({"name": name, "blocks": blocks, "params": params})
    return entry, funcs


def dst(inst):
    m = re.match(r"\.(?:pure|ne|word|low|heapFloor|alloc) (\d+)", inst) or re.match(
        r"\.effect \(some (\d+)\)", inst
    )
    return int(m.group(1)) if m else None


def succs(term):
    m = re.match(r"\.jump (\d+)", term)
    if m:
        return [int(m.group(1))]
    m = re.match(r"\.branch \(.*?\) (\d+) (\d+)", term)
    if m:
        return [int(m.group(1)), int(m.group(2))]
    m = re.match(r"\.switch \(.*?\) (\d+) \[(.*)\]", term)
    if m:
        return [int(m.group(1))] + [
            int(x) for x in re.findall(r", (\d+)\)", m.group(2))
        ]
    return []


def reach(blocks, start, avoid=None):
    seen, todo = set(), [start]
    while todo:
        b = todo.pop()
        if b in seen or b == avoid:
            continue
        seen.add(b)
        todo.extend(succs(blocks[b]["term"]))
    return seen


def lean_expr(e):
    if e[0] == "lit":
        return f"(.lit {e[1]})"
    if e[0] == "arg":
        return f"(.arg {e[1]})"
    if e[0] == "init":
        return f"(.init {e[1]})"
    return f"(.bin .{e[1]} {lean_expr(e[2])} {lean_expr(e[3])})"


def main():
    if len(sys.argv) != 7:
        die("usage: loop_equiv.py MANIFEST STAGE0 FUNCTION SELECTOR NARGS OUT")
    with open(sys.argv[1], encoding="utf-8") as f:
        manifest = json.load(f)
    with open(sys.argv[2], encoding="utf-8") as f:
        text = f.read()
    fname, sel, nargs, out = (
        sys.argv[3],
        int(sys.argv[4], 0),
        int(sys.argv[5]),
        sys.argv[6],
    )
    if manifest.get("format") != "solar-verify loop heads 1":
        die("unknown manifest format")
    entries = [
        f for f in manifest["functions"] if f["function"].split(".")[-1] == fname
    ]
    if len(entries) != 1 or len(entries[0]["loops"]) != 1:
        die(f"{fname}: need exactly one loop in the manifest")
    entry, funcs = parse_module(text)
    idx = [i for i, f in enumerate(funcs) if f["name"] == fname]
    if len(idx) != 1:
        die(f"{fname}: not in the module")
    fn = idx[0]
    blocks = funcs[fn]["blocks"]
    heads = [
        h
        for h, b in enumerate(blocks)
        if b["phis"]
        and any(p in reach(blocks, h) for _, arms in b["phis"] for p, _ in arms)
    ]
    if len(heads) != 1:
        die(f"{fname}: need exactly one loop header in the MIR, found {len(heads)}")
    head = heads[0]
    pre = {b for b in reach(blocks, 0, avoid=head) if head in reach(blocks, b)}
    after = reach(blocks, head)
    loop = {b for b in reach(blocks, head) if head in reach(blocks, b)} - {head}
    slots, mem, nhw = {}, {}, [0]

    def fresh():
        nhw[0] += 1
        return nhw[0] - 1

    # The header's phis, then the loop's values, are header words.
    for d, _ in blocks[head]["phis"]:
        slots[d] = ("hw", fresh())
    for b in sorted(loop | {head}):
        for i in blocks[b]["insts"]:
            if re.match(r"\.effect none \.sstore", i):
                die(f"{fname}: a storage write in the loop")
            d = dst(i)
            if d is not None and d not in slots:
                slots[d] = ("hw", fresh())
    # Memory at constant offsets: shared with the value an assume pins it to.
    pins = {}
    for b in sorted(after):
        loads = {}
        for i in blocks[b]["insts"]:
            m = re.match(r"\.effect \(some (\d+)\) \.mload \[\.const (\d+)\]", i)
            if m:
                loads[int(m.group(1))] = int(m.group(2))
            m = re.match(r"\.assume false \.eq \[\.value (\d+), \.value (\d+)\]", i)
            if m:
                a, c = int(m.group(1)), int(m.group(2))
                if a in loads and c in slots:
                    pins[loads[a]] = c
    for b in sorted(loop | pre | {head}):
        for i in blocks[b]["insts"]:
            m = re.match(r"\.effect none \.mstore \[\.const (\d+),", i)
            if m:
                o = int(m.group(1))
                if o not in mem:
                    mem[o] = (
                        slots[pins[o]]
                        if o in pins and pins[o] in slots
                        else ("hw", fresh())
                    )
    # The values before the header.
    stored = set()
    for b in sorted(pre):
        for i in blocks[b]["insts"]:
            if re.match(r"\.effect none \.sstore", i):
                die(f"{fname}: a storage write before the loop")
    for b in sorted(pre):
        for i in blocks[b]["insts"]:
            d = dst(i)
            if d is None or d in slots:
                continue
            m = re.match(r"\.effect \(some \d+\) \.calldataload \[\.const (\d+)\]", i)
            k = re.match(r"\.effect \(some \d+\) \.sload \[\.const (\d+)\]", i)
            if (
                m
                and (int(m.group(1)) - 4) % 32 == 0
                and (int(m.group(1)) - 4) // 32 < nargs
            ):
                slots[d] = ("fixed", ("arg", (int(m.group(1)) - 4) // 32))
            elif k and int(k.group(1)) not in stored:
                slots[d] = ("fixed", ("init", int(k.group(1))))
            else:
                slots[d] = ("hw", fresh())
    # The entry function's values are 0 after its tail call.
    for b in funcs[entry]["blocks"]:
        for i in b["insts"]:
            d = dst(i)
            if d is not None and d not in slots:
                slots[d] = ("fixed", ("lit", 0))

    def word(v):
        s = slots.get(v)
        if s is None:
            return None
        return ("arg", nargs + s[1]) if s[0] == "hw" else s[1]

    # The cases: the loop's assumes on header comparisons hold, or the header's branch exits.
    pure = {}
    for b in sorted(loop | {head}):
        for i in blocks[b]["insts"]:
            m = re.match(
                r"\.pure (\d+) \.(\w+) \[\.value (\d+), (\.const (\w+)|\.value (\d+))\]",
                i,
            )
            if m:
                pure[int(m.group(1))] = (
                    m.group(2),
                    int(m.group(3)),
                    ("lit", int(m.group(5), 0))
                    if m.group(5)
                    else ("val", int(m.group(6))),
                )
    facts = []
    for b in sorted(loop):
        for i in blocks[b]["insts"]:
            m = re.match(r"\.assume false \.eq \[\.value (\d+), \.const 0\]", i)
            if m and int(m.group(1)) in pure:
                op, a, c = pure[int(m.group(1))]
                rhs = c if c[0] == "lit" else word(c[1])
                if word(a) is not None and rhs is not None:
                    facts.append((("bin", op, word(a), rhs), "false"))
    bm = re.match(r"\.branch \(\.value (\d+)\) ", blocks[head]["term"])
    if not bm or int(bm.group(1)) not in pure:
        die(f"{fname}: the header does not branch on a comparison")
    op, a, c = pure[int(bm.group(1))]
    exitc = ("bin", op, word(a), c if c[0] == "lit" else word(c[1]))
    cases = [facts, [(exitc, "false")]]

    def slot(s):
        return f"(.hw {s[1]})" if s[0] == "hw" else f"(.fixed {lean_expr(s[1])})"

    ids = ",\n      ".join(f"({v}, {slot(s)})" for v, s in sorted(slots.items()))
    mems = ", ".join(f"({o}, {slot(s)})" for o, s in sorted(mem.items()))
    cs = ", ".join(
        "[" + ", ".join(f"({lean_expr(e)}, {b})" for e, b in F) + "]" for F in cases
    )
    with open(out, "w", encoding="utf-8") as f:
        f.write(
            HEADER.format(
                fname=fname,
                sel=sel,
                fn=fn,
                head=head,
                ids=ids,
                mems=mems,
                nhw=nhw[0],
                cases=cs,
                fuel=4 * sum(len(fb["blocks"]) for fb in funcs) + 8,
            )
        )


if __name__ == "__main__":
    main()
