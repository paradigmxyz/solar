"""Tests of the loop cut-point certificate writer (tools/certify/loop_equiv.py).

  python3 tools/certify/test_loop_equiv.py

They need neither Lean nor solar. testdata/loop_equiv/Bump.Stage0.lean is the `Stage0.lean` that
`solar Bump.sol --emit=bin-runtime -Ogas --evm-version osaka -Zemit-lean-stages=DIR` writes
for testdata/loop_equiv/Bump.sol, and Bump.loop-heads.json is a manifest in solar-verify's
loop-head format for it. The certificate is only an input to a kernel check, so these tests pin
what the writer reads and writes, never that the certificate holds.
"""

import contextlib
import io
import json
import pathlib
import sys
import tempfile
import unittest

HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import loop_equiv

DATA = HERE / "testdata" / "loop_equiv"
STAGE0 = DATA / "Bump.Stage0.lean"
MANIFEST = DATA / "Bump.loop-heads.json"
EXPECTED = """import Verify.LoopSource.Equiv.Cut

/-! Generated by `tools/certify/loop_equiv.py` for `bump` (selector 0xb20eb4c4); do not edit. -/

namespace Verify.LoopSource.Equiv.Generated
open SolidCore.Refinement.Generic Verify.LoopSource.Equiv

/-- The cut-point certificate of `bump`'s loop. -/
def cut : Cut :=
  { fn := 0, head := 1,
    ids := [
      (0, (.fixed (.lit 0))),
      (2, (.fixed (.lit 0))),
      (3, (.hw 0)),
      (4, (.hw 3)),
      (6, (.fixed (.lit 0))),
      (10, (.hw 6)),
      (14, (.fixed (.init 0))),
      (20, (.hw 4)),
      (21, (.hw 5)),
      (30, (.hw 1)),
      (31, (.hw 2)),
      (33, (.hw 7)),
      (35, (.hw 8)),
      (37, (.fixed (.arg 0))),
      (43, (.hw 9))],
    mem := [], writes := [], nhw := 10,
    cases := [[]],
    fuel := 64 }

end Verify.LoopSource.Equiv.Generated
"""


def run(manifest, stage0, fname="bump", sel="0xb20eb4c4", nargs="1"):
    """loop_equiv.main on the given texts: its exit status, its error output and what it wrote."""
    with tempfile.TemporaryDirectory() as tmp:
        tmp = pathlib.Path(tmp)
        (tmp / "m.json").write_text(manifest, encoding="utf-8")
        (tmp / "Stage0.lean").write_text(stage0, encoding="utf-8")
        out = tmp / "Cut.lean"
        argv = ["loop_equiv.py", str(tmp / "m.json"), str(tmp / "Stage0.lean")]
        argv += [fname, sel, nargs, str(out)]
        err = io.StringIO()
        old, sys.argv = sys.argv, argv
        try:
            with contextlib.redirect_stderr(err):
                loop_equiv.main()
            status = 0
        except SystemExit as e:
            status = e.code
        finally:
            sys.argv = old
        return status, err.getvalue(), (out.read_text() if out.exists() else None)


class Parse(unittest.TestCase):
    def test_module(self):
        entry, funcs = loop_equiv.parse_module(STAGE0.read_text())
        self.assertEqual(entry, 1)
        self.assertEqual([f["name"] for f in funcs], ["bump", "entry"])
        self.assertEqual([len(f["blocks"]) for f in funcs], [10, 4])
        head = funcs[0]["blocks"][1]
        self.assertEqual(
            head["phis"],
            [
                (3, [(9, ".value 43"), (7, ".value 10")]),
                (30, [(9, ".value 14"), (7, ".value 20")]),
                (31, [(9, ".const 0"), (7, ".const 1")]),
            ],
        )
        self.assertEqual(head["insts"], [".ne 4 (.value 3) (.const 0)"])
        self.assertEqual(head["term"], ".branch (.value 4) 3 4")
        self.assertEqual(
            funcs[0]["blocks"][9]["insts"],
            [
                ".effect (some 37) .calldataload [.const 4]",
                ".effect (some 14) .sload [.const 0]",
                ".pure 43 .sub [.const 0, .value 37]",
            ],
        )
        self.assertEqual(loop_equiv.succs(funcs[1]["blocks"][1]["term"]), [3, 2])

    def test_values(self):
        self.assertEqual(loop_equiv.dst(".pure 20 .add [.value 30, .const 1]"), 20)
        self.assertEqual(loop_equiv.dst(".ne 4 (.value 3) (.const 0)"), 4)
        self.assertEqual(loop_equiv.dst(".effect (some 14) .sload [.const 0]"), 14)
        self.assertIsNone(loop_equiv.dst(".effect none .sstore [.const 0, .value 30]"))


class Certificate(unittest.TestCase):
    def test_bump(self):
        status, err, out = run(MANIFEST.read_text(), STAGE0.read_text())
        self.assertEqual((status, err), (0, ""))
        self.assertEqual(out, EXPECTED)

    def test_storage_write_in_loop(self):
        # The loop's increment block (bb7) also writes the counter to storage.
        stage0 = STAGE0.read_text().replace(
            "[.pure 10 .add [.value 3, .const 1]],",
            "[.pure 10 .add [.value 3, .const 1],\n"
            "         .effect none .sstore [.const 0, .value 20]],",
        )
        self.assertNotEqual(stage0, STAGE0.read_text())
        status, err, out = run(MANIFEST.read_text(), stage0)
        self.assertEqual(status, 2)
        self.assertEqual(err, "loop_equiv: bump: a storage write in the loop\n")
        self.assertIsNone(out)

    def test_manifest_without_loop(self):
        manifest = json.loads(MANIFEST.read_text())
        manifest["functions"][0]["loops"] = []
        status, err, out = run(json.dumps(manifest), STAGE0.read_text())
        self.assertEqual(status, 2)
        self.assertEqual(
            err, "loop_equiv: bump: need exactly one loop in the manifest\n"
        )
        self.assertIsNone(out)

    def test_unknown_manifest_format(self):
        manifest = json.loads(MANIFEST.read_text())
        manifest["format"] = "solar-verify loop heads 2"
        status, err, out = run(json.dumps(manifest), STAGE0.read_text())
        self.assertEqual(status, 2)
        self.assertEqual(err, "loop_equiv: unknown manifest format\n")
        self.assertIsNone(out)


if __name__ == "__main__":
    unittest.main()
