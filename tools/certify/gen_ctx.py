#!/usr/bin/env python3
"""Write the context checker's certificate module of a contract's exported stages (untrusted).

gen_ctx.py GEN_DIR --module-prefix NAME.gen.C --contract C --final evmN --out OUT.lean

The module states the certificate asm_ctxl.infer_ctx inferred as data, proves by the kernel's
evaluation that AssembleCtx.checkXB accepts the exact bytecode against the final EVM IR in its
effect form (checkXB (norm evmN)), and instantiates AssembleCtx.assembly_of_checkXB_norm.
"""
import argparse, pathlib, sys
sys.path.insert(0, str(pathlib.Path(__file__).parent))
import asm_ctxl

ap = argparse.ArgumentParser()
ap.add_argument("gen", type=pathlib.Path)
ap.add_argument("--module-prefix", required=True)
ap.add_argument("--contract", required=True)
ap.add_argument("--final", required=True)
ap.add_argument("--out", required=True, type=pathlib.Path)
a = ap.parse_args()
final_mod = a.final[0].upper() + a.final[1:]
text = (a.gen / f"{final_mod}.lean").read_text()
hexs = (a.gen / "manifest.json").read_text()
import json
code = bytes.fromhex(json.loads(hexs)["bytecode"])
c = asm_ctxl.infer_ctx(text, code)
ns = f"SolarTV.Export.{a.contract}.Ctx"
out = f"""import {a.module_prefix}.{final_mod}
import {a.module_prefix}.Bytecode
import SolidCore.Refinement.Solar.AssembleCtxCall

-- Generated by solar's tools/certify/gen_ctx.py from the run's export; do not edit.

/-!
# {a.contract}: the exact bytecode against the final EVM IR, by the checker with contexts

`cx` is tools/certify/asm_ctxl.py's inferred certificate (untrusted data): one context per entry
height range, entry types and return labels of each block. `check_ok`: the kernel evaluates
`AssembleCtx.checkXB` of `{a.final}` in its effect form against the exact bytecode.
`bytecode`: `assembly_of_checkXB_norm`, at every gas below `2 ^ 256`.
-/

namespace {ns}

open SolidCore.Refinement.Solar SolidCore.Refinement.Solar.AssembleCtx

/-- The exact runtime bytecode, byte by byte. -/
abbrev bytes : List Nat := SolarTV.Export.{a.contract}.bytecode

def code : ByteArray := ⟨(bytes.map UInt8.ofNat).toArray⟩

/-- The final EVM IR. -/
abbrev prog : SolarTV.Assembly.Program := SolarTV.Export.{a.contract}.{a.final}

def cx : CtxCert :=
  {asm_ctxl.lean_ctx_cert(c)}

set_option maxRecDepth 100000 in
theorem check_ok : checkXB (norm prog) code cx = true := by decide +kernel

/-- **The exact bytecode runs as the final EVM IR**, at every gas below `2 ^ 256`, under the
checker's named hypotheses on the runner of messages. -/
theorem bytecode (codes : SolidCore.Solidity.Shared.Account.BytesMap) (scope : SolarTV.Call → Prop)
    (hP : ∀ gas, AssembleCallSeg.StaticRunner gas)
    (hQ : ∀ gas call, scope call → AssembleCallSeg.CalleesRun gas code call) :
    ∀ gas, gas < 2 ^ 256 → ∀ call, scope call → ∃ (o : SolarTV.Machine.Oracle) (W : SolidCore.Refinement.World),
      W.Open ∧ AssembleCall.CallsAgree o W ∧ RunOracle.CertOk cx.base o ∧
      SolarTV.Within (SolarTV.evmirSem o) (SolidCore.Refinement.Final.ethLibWith gas) prog code (· = call) :=
  assembly_of_checkXB_norm check_ok codes scope hP hQ

/-- info: '{ns}.bytecode' depends on axioms: [propext, Classical.choice, Quot.sound] -/
#guard_msgs (whitespace := lax) in
#print axioms bytecode

end {ns}
"""
a.out.write_text(out)
print(f"{ns}.bytecode")
