#!/usr/bin/env python3
"""The source stage of a self-recursive function: bind solidity-lean's Verify/Phase3/RecSource to a
Solidity file (Phase 3, slice 4; see RECURSION.md).

The generic source stage erases a function's body to a finite tree (eraseStmt) and inlines every
internal call it erases, so a function that calls itself has no erasure and the driver refuses it
there. solidity-lean's Verify/Phase3/RecSource proves the source side instead by induction on the
function's @custom:decreases measure, in SolidCore's own interpreter: `sum_runs` (the recursive
function's body returns its value from every entry at a measure, the recursive call running by the
theorem at the lower measure through SolidCore's internal-call semantics), `total_runs` (the caller's
body as BodyRuns, so the generic dispatcher theorem `runtime_run_clean` applies) and
`source_to_bytecode` (the source's result joined to the bytecode theorem of the backend stages,
Verify/Phase3/RecSum/Bytecode.lean's `total_returns_bytecode`).

Those proofs are about the SolidCore AST in RecSource/Ast.lean. This script is what makes them about a
file: it runs the same solc-AST front end the generic driver runs (scripts/solc_ast_to_lean_source.py,
on a copy at the path generic.frontend fixes by the source's digest) and requires its output to be
Ast.lean's body byte for byte, refusing otherwise with the first differing line. Source.lean's
`shape_eq` then checks in the kernel that the type checker's contract of that AST has the function
bodies the induction runs. A source that is not the one the proofs are about is refused, never
proved:

    rec_source.py SOURCE --solidity-lean DIR [--solc SOLC] [--write]

--write regenerates Ast.lean from SOURCE instead (for a new source; its proofs must then be redone).
Exit 0: bound; 1: refused (the reason on stderr); 2: usage or tool failure.
"""

import argparse
import hashlib
import os
import pathlib
import re
import shutil
import subprocess
import sys

NAMESPACE = "Verify.Phase3.RecSource.Ast"
MODULE = pathlib.Path("Verify/Phase3/RecSource/Ast.lean")
HEADER = (
    "-- Generated by solar's tools/certify/rec_source.py with scripts/solc_ast_to_lean_source.py from\n"
    "-- the source whose sha256 is {sha}; do not edit.\n"
    "\nimport SolidCore.Solidity.Checked\n\nopen SolidCore.Solidity\n\n"
)
SOLC_VERSION = "0.8.35"


def frontend(lean_dir, src, solc):
    """The front end's body of SRC, as generic.frontend runs it: on a copy at a path fixed by the
    source's digest, so the recorded importedSourceName is the same wherever SRC sits."""
    text = pathlib.Path(src).read_bytes()
    sha = hashlib.sha256(text).hexdigest()
    base = re.sub(r"[^a-z0-9_]", "_", pathlib.Path(src).stem.lower()).strip("_") or "c"
    if not base[0].isalpha():
        base = "c_" + base
    fe = pathlib.Path("/tmp/solar-certify-src") / sha
    fe.mkdir(parents=True, exist_ok=True)
    copy = fe / f"{base}_{sha[:8]}.sol"
    shutil.copy(src, copy)
    r = subprocess.run(
        [sys.executable, str(pathlib.Path(lean_dir) / "scripts/solc_ast_to_lean_source.py"), str(copy),
         "--contract", "RecSum", "--solc", solc, "--namespace", NAMESPACE, "--body-only"],
        capture_output=True, text=True,
    )
    if r.returncode != 0:
        raise SystemExit(f"rec_source: front end failed: {r.stderr.strip()[-400:]}")
    return sha, r.stdout


def module_text(sha, body):
    return HEADER.format(sha=sha) + body


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("source")
    ap.add_argument("--solidity-lean", required=True)
    ap.add_argument("--solc", default=os.environ.get(
        "SOLC", str(pathlib.Path.home() / ".cache/solc" / f"solc-{SOLC_VERSION}")))
    ap.add_argument("--write", action="store_true")
    a = ap.parse_args(argv)
    sha, body = frontend(a.solidity_lean, a.source, a.solc)
    want = module_text(sha, body)
    path = pathlib.Path(a.solidity_lean) / MODULE
    if a.write:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(want)
        print(f"rec_source: wrote {path} from {a.source} ({sha})")
        return 0
    if not path.is_file():
        print(f"rec_source: REFUSED: {path} does not exist", file=sys.stderr)
        return 1
    have = path.read_text()
    if have != want:
        for i, (x, y) in enumerate(zip(have.splitlines(), want.splitlines()), 1):
            if x != y:
                print(f"rec_source: REFUSED: {MODULE} is not the front end's AST of {a.source}: line {i}: "
                      f"module {x[:120]!r}, source {y[:120]!r}", file=sys.stderr)
                return 1
        print(f"rec_source: REFUSED: {MODULE} is not the front end's AST of {a.source}: lengths differ",
              file=sys.stderr)
        return 1
    print(f"rec_source: bound: {MODULE} is the front end's AST of {a.source} ({sha}); the source "
          "stage is Verify.Phase3.RecSource.Join.source_to_bytecode")
    return 0


if __name__ == "__main__":
    sys.exit(main())
