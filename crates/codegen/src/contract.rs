/// Generated bytecode and optional intermediate representations for one contract.
#[derive(Clone, Debug, Default)]
pub struct ContractArtifact {
    /// Deployment bytecode.
    pub deployment: Bytes,
    /// Runtime bytecode.
    pub runtime: Bytes,
    /// Immutable placeholders in the runtime bytecode.
    pub immutable_references: Vec<ImmutableReference>,
    /// Unresolved library addresses in the deployment bytecode.
    pub deployment_link_references: Vec<LibraryReference>,
    /// Unresolved library addresses in the runtime bytecode.
    pub runtime_link_references: Vec<LibraryReference>,
    /// The [`RuntimeDataFn`] values of this contract and the contracts it embeds in the deployment
    /// bytecode, in ascending order.
    pub deployment_trailers: Vec<Trailer>,
    /// The [`RuntimeDataFn`] values of this contract and the contracts it embeds in the runtime
    /// bytecode, in ascending order.
    pub runtime_trailers: Vec<Trailer>,
    /// Captured MIR, built under `-O none` without an explicit pipeline, and
    /// post-pipeline otherwise.
    pub mir: Option<Module>,
    /// Lowered MIR retained independently of the built snapshot.
    pub final_mir: Option<Module>,
    /// Final deployment-prefix EVM IR immediately before byte emission.
    pub deployment_evm_ir: Option<ir::Module>,
    /// Final runtime EVM IR immediately before byte emission.
    pub runtime_evm_ir: Option<ir::Module>,
    /// Runtime EVM IR as stack scheduling emitted it, before the EVM IR pipeline.
    pub runtime_scheduled_evm_ir: Option<ir::Module>,
    /// Final deployment-prefix instruction locations.
    pub deployment_debug_info: Option<DebugInfo>,
    /// Final runtime instruction locations.
    pub runtime_debug_info: Option<DebugInfo>,
}

/// An immutable placeholder in runtime bytecode.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct ImmutableReference {
    /// Source variable containing the immutable declaration.
    ///
    /// `None` for a library's own deployment address, which guards its non-view functions
    /// against direct calls and is reported as [`Self::LIBRARY_DEPLOY_ADDRESS`], like solc's
    /// IR pipeline.
    pub variable_id: Option<VariableId>,
    /// Byte offset where the placeholder data begins.
    pub start: usize,
    /// Type width encoded by the placeholder.
    pub type_size: TypeSize,
}

impl ImmutableReference {
    /// The `immutableReferences` key of a library's own deployment address placeholder.
    pub const LIBRARY_DEPLOY_ADDRESS: &str = "library_deploy_address";
}

/// An unresolved library address in generated bytecode.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct LibraryReference {
    /// The library's fully qualified name.
    pub library: QualifiedName,
    /// Byte offset where the address begins.
    pub start: usize,
}

/// Returns opaque data to emit at the end of a contract's runtime program.
pub type RuntimeDataFn<'a> = dyn Fn(ContractId) -> Bytes + Sync + 'a;

/// A contract selection.
#[derive(Clone, Debug)]
pub enum ContractSelection {
    /// Generate only the listed contracts and their dependencies.
    Specific(DenseBitSet<ContractId>),
    /// Generate every deployable contract.
    All,
}

impl ContractSelection {
    /// Creates an empty contract selection.
    pub fn empty(gcx: Gcx<'_>) -> Self {
        Self::Specific(DenseBitSet::new_empty(gcx.hir.contract_ids().len()))
    }

    /// Returns the specific contracts or every deployable contract.
    pub fn into_iter<'a, 'gcx>(
        &'a self,
        gcx: Gcx<'gcx>,
    ) -> impl Iterator<Item = ContractId> + use<'a, 'gcx> {
        match self {
            Self::Specific(contracts) => Either::Left(contracts.iter()),
            Self::All => Either::Right(gcx.hir.contract_ids().filter(move |&contract_id| {
                let contract = gcx.hir.contract(contract_id);
                !contract.kind.is_interface() && !contract.kind.is_abstract_contract()
            })),
        }
    }

    /// Adds another selection to this one.
    pub fn union_with(&mut self, other: &Self) {
        match other {
            Self::Specific(other) => {
                if let Self::Specific(contracts) = self {
                    contracts.union(other);
                }
            }
            Self::All => *self = Self::All,
        }
    }

    /// Selects `contract_id`.
    pub fn insert(&mut self, contract_id: ContractId) {
        if let Self::Specific(contracts) = self {
            contracts.insert(contract_id);
        }
    }

    /// Returns whether no contracts are selected.
    pub fn is_empty(&self) -> bool {
        matches!(self, Self::Specific(contracts) if contracts.is_empty())
    }

    /// Returns whether `contract_id` is selected.
    fn contains(&self, contract_id: ContractId) -> bool {
        match self {
            Self::Specific(contracts) => contracts.contains(contract_id),
            Self::All => true,
        }
    }
}

/// Generates requested contract artifacts and their creation-bytecode dependencies.
///
/// Contracts in `contracts` retain bytecode in the returned artifact.
/// Contracts in `capture_mir` retain built MIR under `-O none` when no explicit pipeline is
/// configured and final MIR otherwise, and, with `-Zdump=mir-final`, the final MIR in
/// `final_mir`.
/// Contracts in `capture_evm_ir` retain their final EVM IR in the returned artifact.
/// Values returned by `runtime_data` are emitted as trailing runtime program data.
/// Contracts in `capture_debug_info` retain final instruction locations.
#[tracing::instrument(name = "codegen", level = "debug", skip_all)]
pub fn generate_contract_bytecodes(
    gcx: Gcx<'_>,
    contracts: &ContractSelection,
    capture_mir: &ContractSelection,
    capture_evm_ir: &ContractSelection,
    runtime_data: Option<&RuntimeDataFn<'_>>,
    capture_debug_info: &ContractSelection,
) -> Result<FxHashMap<ContractId, ContractArtifact>> {
    // The bytecode of a failed compilation is withheld, and lowering reports the
    // construct that analysis already rejected as a second, misleading error.
    gcx.dcx().has_errors()?;
    let captures = ContractCaptures {
        bytecode: contracts,
        mir: capture_mir,
        evm_ir: capture_evm_ir,
        runtime_data,
        debug_info: capture_debug_info,
    };
    let mut requested = contracts.clone();
    requested.union_with(capture_mir);
    requested.union_with(capture_evm_ir);
    requested.union_with(capture_debug_info);
    let graph = ContractGraph::discover(gcx, &requested)?;
    let contract_count = gcx.hir.contract_ids().len();

    let parallel = gcx.sess.is_parallel_codegen();
    let priorities = if parallel {
        graph.scheduling_priorities(gcx)
    } else {
        // Keep source order, with each contract after the contracts it embeds, so no scheduled
        // contract waits on another.
        let mut priorities = IndexVec::from_vec(vec![0; contract_count]);
        for (rank, &contract_id) in graph.order.iter().rev().enumerate() {
            priorities[contract_id] = rank as u64 + 1;
        }
        priorities
    };
    let jobs = ContractJobs {
        gcx,
        span: tracing::Span::current(),
        captures,
        graph: &graph,
        artifacts: IndexVec::from_vec((0..contract_count).map(|_| OnceLock::new()).collect()),
        scheduled: IndexVec::from_vec((0..contract_count).map(|_| Mutex::new(None)).collect()),
        diagnostics: IndexVec::from_vec((0..contract_count).map(|_| Mutex::default()).collect()),
        remaining_inputs: IndexVec::from_vec(
            graph
                .dependencies
                .iter()
                .map(|dependencies| AtomicUsize::new(dependencies.len() + 1))
                .collect(),
        ),
        queue: ContractQueue::new(gcx.sess, &graph, priorities),
        parallel,
    };
    // Every contract is queued up front; only its completion waits for the bytecode of the
    // contracts it creates.
    for contract_id in graph.reachable.iter() {
        jobs.queue.push_schedule(contract_id);
    }
    sync::scope(parallel, |scope| {
        for _ in graph.reachable.iter() {
            jobs.spawn_worker(&scope);
        }
    });
    // Only code generation reads the plans; free them before the output phase.
    gcx.codegen_state::<CodegenState>().clear_plans();
    let artifacts = jobs.artifacts;
    // Emit the diagnostics in the order of a sequential run: contracts in source order, each after
    // the contracts it embeds.
    let mut diagnostics = jobs.diagnostics;
    for &contract_id in &graph.order {
        gcx.dcx().emit_deferred(std::mem::take(diagnostics[contract_id].get_mut()));
    }
    gcx.dcx().has_errors()?;

    let mut generated = FxHashMap::default();
    for (contract_id, artifact) in artifacts.into_iter_enumerated() {
        if graph.reachable.contains(contract_id) {
            generated.insert(
                contract_id,
                artifact.into_inner().expect("contract artifact should have been generated"),
            );
        }
    }
    Ok(generated)
}

/// Generates the bytecode of a lowered MIR module given as input. Its pipeline already ran, so
/// the backend runs no passes of its own, and `module` ends as the final MIR the backend compiled.
/// The artifact keeps the final EVM IR of both programs, which dumps of MIR input print.
///
/// A module given as input comes with no other contract, so data holding another contract's
/// bytecode has nothing to link it to, and is an error.
pub fn generate_mir_input_bytecode(gcx: Gcx<'_>, module: &mut Module) -> Result<EvmArtifact> {
    if let Some(code) = module.data.iter().find_map(|data| match data.bytes {
        DataBytes::Deferred(code) => Some(code),
        DataBytes::Known(_) => None,
    }) {
        let message = "MIR input that embeds another contract's code has no bytecode to emit";
        let note = format!("its data holds `{code}`, which only compiling that contract generates");
        return Err(gcx.dcx().err(message).note(note).emit());
    }
    let mut codegen = EvmCodegen::new(gcx);
    codegen.set_run_pipeline(false);
    codegen.set_capture_mir(true);
    codegen.set_capture_evm_ir(true);
    codegen.set_capture_scheduled_evm_ir(dumps_scheduled_evm_ir(gcx));
    let artifact = codegen.lower_module(module, &EmbeddedBytecodes::default());
    module.backend_memory = artifact.backend_memory.clone();
    gcx.dcx().has_errors()?;
    Ok(artifact)
}

#[derive(Clone, Copy)]
struct ContractCaptures<'a> {
    bytecode: &'a ContractSelection,
    mir: &'a ContractSelection,
    evm_ir: &'a ContractSelection,
    runtime_data: Option<&'a RuntimeDataFn<'a>>,
    debug_info: &'a ContractSelection,
}

struct ContractGraph {
    dependencies: IndexVec<ContractId, GrowableBitSet<ContractId>>,
    dependents: IndexVec<ContractId, Vec<ContractId>>,
    reachable: DenseBitSet<ContractId>,
    /// Reachable contracts in source order, each after the contracts it embeds.
    order: Vec<ContractId>,
}

impl ContractGraph {
    #[tracing::instrument(name = "contract_graph", level = "debug", skip_all)]
    fn discover(gcx: Gcx<'_>, contracts: &ContractSelection) -> Result<Self> {
        let contract_count = gcx.hir.contract_ids().len();
        let mut graph = Self {
            dependencies: IndexVec::from_vec(
                (0..contract_count).map(|_| GrowableBitSet::new_empty()).collect(),
            ),
            dependents: IndexVec::from_vec((0..contract_count).map(|_| Vec::new()).collect()),
            reachable: DenseBitSet::new_empty(contract_count),
            order: Vec::new(),
        };
        let mut visiting = DenseBitSet::new_empty(contract_count);
        for contract_id in contracts.into_iter(gcx) {
            graph.discover_contract(gcx, contract_id, &mut visiting)?;
        }
        Ok(graph)
    }

    fn discover_contract(
        &mut self,
        gcx: Gcx<'_>,
        contract_id: ContractId,
        visiting: &mut DenseBitSet<ContractId>,
    ) -> Result {
        if self.reachable.contains(contract_id) {
            return Ok(());
        }

        let contract = gcx.hir.contract(contract_id);
        if contract.kind.is_interface() || contract.kind.is_abstract_contract() {
            return Err(gcx
                .dcx()
                .err("cannot generate creation bytecode for non-deployable contract")
                .span(contract.span)
                .emit());
        }

        if !visiting.insert(contract_id) {
            return Err(gcx
                .dcx()
                .err("recursive contract creation bytecode dependency")
                .span(contract.span)
                .emit());
        }

        let dependencies = gcx.contract_bytecode_dependencies(contract_id);
        // Final assembly links embedded bytecode by source-qualified name.
        let mut names = FxHashMap::default();
        for dependency in dependencies.iter() {
            let name = crate::link::qualified_name(gcx, dependency);
            if let Some(other) = names.insert(name, dependency) {
                return Err(gcx
                    .dcx()
                    .err(format!("cannot embed two contracts named `{}`", name.as_str()))
                    .span(gcx.hir.contract(dependency).span)
                    .span_note(gcx.hir.contract(other).span, "the other contract is here")
                    .emit());
            }
        }
        for dependency in dependencies.iter() {
            self.dependents[dependency].push(contract_id);
            self.discover_contract(gcx, dependency, visiting)?;
        }
        for dependency in dependencies.iter() {
            self.dependencies[contract_id].insert(dependency);
        }
        self.reachable.insert(contract_id);
        self.order.push(contract_id);
        visiting.remove(contract_id);
        Ok(())
    }

    /// Starts the jobs on the estimated longest remaining path first.
    ///
    /// Scheduling a contract runs concurrently with scheduling the contracts it embeds; only
    /// its short completion waits for them. A contract is therefore done at
    /// `max(schedule end, embedded contracts done) + finish`, and the path from the start of a
    /// contract's scheduling is its own cost plus the finish of itself and of the chain of
    /// contracts that embed it. Source-body sizes are a cheap cost estimate; they do not affect
    /// what gets compiled.
    fn scheduling_priorities(&self, gcx: Gcx<'_>) -> IndexVec<ContractId, u64> {
        // Holds each contract's own cost until the traversal adds its finish chain.
        let mut priorities = IndexVec::from_vec(vec![0u64; self.dependencies.len()]);
        for id in self.reachable.iter() {
            priorities[id] = gcx
                .contract_reachable_functions(id)
                .iter()
                .map(|function| {
                    let span = gcx.hir.function(function).body_span;
                    u64::from(span.hi().to_u32() - span.lo().to_u32())
                })
                .sum::<u64>()
                .max(1);
        }
        // The longest finish chain of the contracts that embed each contract.
        let mut after = IndexVec::from_vec(vec![0; self.dependencies.len()]);
        let mut remaining = IndexVec::from_vec(self.dependents.iter().map(Vec::len).collect());
        let mut ready = self.reachable.iter().filter(|&id| remaining[id] == 0).collect::<Vec<_>>();
        while let Some(id) = ready.pop() {
            let tail = (priorities[id] / FINISH_COST_DIVISOR).saturating_add(after[id]);
            priorities[id] = priorities[id].saturating_add(tail);
            for child in self.dependencies[id].iter() {
                after[child] = after[child].max(tail);
                remaining[child] -= 1;
                if remaining[child] == 0 {
                    ready.push(child);
                }
            }
        }
        priorities
    }
}

/// A contract's completion costs about this fraction of its scheduling, from traces of the heavy
/// projects (2 to 6 percent).
const FINISH_COST_DIVISOR: u64 = 32;

/// One unit of contract code generation.
#[derive(Clone, Copy, Debug, PartialEq, Eq, PartialOrd, Ord)]
enum ContractJob {
    /// Lowers, optimizes, and schedules a contract.
    Schedule(ContractId),
    /// Completes a scheduled contract once the bytecode it embeds is generated.
    Finish(ContractId),
}

/// Workers choose the highest-priority eligible job independently of Rayon's task order.
///
/// A contract whose embedded contracts are unfinished is *early*: it can be scheduled, but its
/// optimized MIR and scheduled EVM IR then stay in memory until the last embedded contract
/// finishes. Scheduling every contract as soon as a worker is free parks dozens of them on
/// large projects, and peak memory grows with that count. At most one early contract per worker
/// thread is in flight, from the start of its scheduling to the end of its completion. Beyond
/// that, workers run only jobs of contracts that are not early. Some early scheduling must stay,
/// because it overlaps a contract's scheduling with its embedded contracts, and a lower limit
/// delays the long contracts on the critical path (2 to 4% of wall time on solady at half the
/// threads).
///
/// A worker that finds no eligible job returns. A job becoming eligible spawns a worker, which
/// happens when a completion is queued, a contract's last embedded contract finishes, an early
/// contract completes, or an error lifts the limit. The contract with no unfinished embedded
/// contracts is always eligible, so the queue never stalls. After an error, the limit is lifted so
/// that every contract still reports its own diagnostics.
struct ContractQueue<'gcx> {
    sess: &'gcx Session,
    state: Mutex<QueueState>,
    priorities: IndexVec<ContractId, u64>,
    /// The most early contracts in flight.
    early_limit: usize,
}

struct QueueState {
    /// Completions and schedulings of contracts that embed no unfinished contract.
    ///
    /// Only these count as queued jobs for [`Session::has_queued_jobs`]: a job that cannot run
    /// leaves the workers free to split other work.
    ready: BinaryHeap<(u64, Reverse<ContractJob>)>,
    /// Schedulings of contracts with unfinished embedded contracts. An entry is stale once
    /// `unfinished_dependencies` reaches zero, because the job then moves to `ready`.
    early: BinaryHeap<(u64, Reverse<ContractJob>)>,
    unfinished_dependencies: IndexVec<ContractId, usize>,
    /// Contracts scheduled early and not yet completed.
    in_flight: DenseBitSet<ContractId>,
    /// Number of `in_flight` contracts.
    in_flight_count: usize,
    unbounded: bool,
}

impl<'gcx> ContractQueue<'gcx> {
    fn new(
        sess: &'gcx Session,
        graph: &ContractGraph,
        priorities: IndexVec<ContractId, u64>,
    ) -> Self {
        // Without worker threads, contracts already run after the contracts they embed.
        let early_limit = if sess.is_parallel_codegen() { sess.threads() } else { 0 };
        Self {
            sess,
            state: Mutex::new(QueueState {
                ready: BinaryHeap::new(),
                early: BinaryHeap::new(),
                unfinished_dependencies: graph.dependencies.iter().map(|d| d.count()).collect(),
                in_flight: DenseBitSet::new_empty(graph.dependencies.len()),
                in_flight_count: 0,
                unbounded: false,
            }),
            priorities,
            early_limit,
        }
    }

    fn push_schedule(&self, contract_id: ContractId) {
        let entry = (self.priorities[contract_id], Reverse(ContractJob::Schedule(contract_id)));
        let mut state = self.state.lock();
        if state.unfinished_dependencies[contract_id] == 0 {
            self.sess.queue_job();
            state.ready.push(entry);
        } else {
            state.early.push(entry);
        }
    }

    fn push_finish(&self, contract_id: ContractId) {
        self.sess.queue_job();
        let entry = (u64::MAX, Reverse(ContractJob::Finish(contract_id)));
        self.state.lock().ready.push(entry);
    }

    /// Records a finished embedded contract of `contract_id`. Returns whether this makes its
    /// scheduling eligible.
    fn dependency_finished(&self, contract_id: ContractId) -> bool {
        let mut state = self.state.lock();
        state.unfinished_dependencies[contract_id] -= 1;
        if state.unfinished_dependencies[contract_id] != 0 || state.in_flight.contains(contract_id)
        {
            return false;
        }
        self.sess.queue_job();
        state
            .ready
            .push((self.priorities[contract_id], Reverse(ContractJob::Schedule(contract_id))));
        true
    }

    /// Records that `contract_id` is complete. Returns whether this frees a slot for a waiting
    /// early contract.
    fn complete(&self, contract_id: ContractId) -> bool {
        let mut state = self.state.lock();
        if !state.in_flight.remove(contract_id) {
            return false;
        }
        state.in_flight_count -= 1;
        !state.early.is_empty()
    }

    /// Lifts the limit on early contracts. Returns the number of early jobs that become eligible.
    fn lift_limit(&self) -> usize {
        let mut state = self.state.lock();
        if mem::replace(&mut state.unbounded, true) { 0 } else { state.early.len() }
    }

    /// Takes the highest-priority eligible job, if any.
    fn pop(&self) -> Option<ContractJob> {
        let mut state = self.state.lock();
        while let Some(&(_, Reverse(ContractJob::Schedule(id)))) = state.early.peek()
            && state.unfinished_dependencies[id] == 0
        {
            state.early.pop();
        }
        let may_park = state.unbounded || state.in_flight_count < self.early_limit;
        let take_early = may_park
            && match (state.ready.peek(), state.early.peek()) {
                (_, None) => false,
                (None, Some(_)) => true,
                (Some(ready), Some(early)) => early > ready,
            };
        if take_early {
            let (_, Reverse(job)) = state.early.pop()?;
            let ContractJob::Schedule(id) = job else { unreachable!("only schedulings are early") };
            state.in_flight.insert(id);
            state.in_flight_count += 1;
            return Some(job);
        }
        let (_, Reverse(job)) = state.ready.pop()?;
        self.sess.start_job();
        Some(job)
    }
}

/// A contract that is optimized and scheduled, waiting for the bytecode it embeds.
struct ScheduledContract<'gcx> {
    module: Module,
    /// Code generation waiting for linking, runtime assembly, and deployment code, if the
    /// contract has code.
    codegen: Option<Box<EvmCodegen<'gcx>>>,
    /// MIR captured before the optimization pipeline.
    built_mir: Option<Module>,
}

/// Shared state of the contract code generation jobs.
struct ContractJobs<'a, 'gcx> {
    gcx: Gcx<'gcx>,
    /// Parent of the job spans, which run on worker threads.
    span: tracing::Span,
    captures: ContractCaptures<'a>,
    graph: &'a ContractGraph,
    artifacts: IndexVec<ContractId, OnceLock<ContractArtifact>>,
    scheduled: IndexVec<ContractId, Mutex<Option<ScheduledContract<'gcx>>>>,
    /// Diagnostics of each contract's jobs, withheld because the jobs run in any order.
    diagnostics: IndexVec<ContractId, Mutex<DeferredDiagnostics>>,
    /// Unfinished inputs of each contract: its own scheduling and each dependency.
    remaining_inputs: IndexVec<ContractId, AtomicUsize>,
    queue: ContractQueue<'gcx>,
    parallel: bool,
}

impl<'a, 'gcx> ContractJobs<'a, 'gcx> {
    /// Spawns a worker that runs the highest-priority eligible job, if there is one.
    fn spawn_worker<'scope>(&'scope self, scope: &Scope<'_, 'scope>) {
        scope.spawn(move |scope| {
            let Some(job) = self.queue.pop() else { return };
            match job {
                ContractJob::Schedule(contract_id) => {
                    let Ok(scheduled) = self.schedule(contract_id) else {
                        return self.lift_limit(&scope);
                    };
                    *self.scheduled[contract_id].lock() = Some(scheduled);
                    self.release(&scope, contract_id);
                }
                ContractJob::Finish(contract_id) => {
                    let scheduled = self.scheduled[contract_id]
                        .lock()
                        .take()
                        .expect("contract should be scheduled before it finishes");
                    let Ok(artifact) = self.finish(contract_id, scheduled) else {
                        return self.lift_limit(&scope);
                    };
                    self.artifacts[contract_id]
                        .set(artifact)
                        .expect("contract artifact should only be generated once");
                    for &dependent in &self.graph.dependents[contract_id] {
                        if self.queue.dependency_finished(dependent) {
                            self.wake_worker(&scope);
                        }
                        self.release(&scope, dependent);
                    }
                    if self.queue.complete(contract_id) {
                        self.wake_worker(&scope);
                    }
                }
            }
        });
    }

    /// Spawns a worker for a job that became eligible. Without threads, a spawn runs inline and
    /// would nest the next contract in this one, and the workers spawned up front already cover
    /// every job.
    fn wake_worker<'scope>(&'scope self, scope: &Scope<'_, 'scope>) {
        if self.parallel {
            self.spawn_worker(scope);
        }
    }

    /// Lets every contract report its own diagnostics after an error: the failed contract's
    /// dependents never complete, so they would hold their early slots forever.
    fn lift_limit<'scope>(&'scope self, scope: &Scope<'_, 'scope>) {
        for _ in 0..self.queue.lift_limit() {
            self.spawn_worker(scope);
        }
    }

    /// Records one finished input of `contract_id` and completes it after the last one.
    fn release<'scope>(&'scope self, scope: &Scope<'_, 'scope>, contract_id: ContractId) {
        let previous = self.remaining_inputs[contract_id].fetch_sub(1, Ordering::AcqRel);
        assert!(previous > 0, "contract input count underflow");
        if previous == 1 {
            self.queue.push_finish(contract_id);
            self.spawn_worker(scope);
        }
    }

    /// Runs `job` for `contract_id`, withholding its diagnostics until every job is done.
    fn defer_diagnostics<R>(&self, contract_id: ContractId, job: impl FnOnce() -> R) -> R {
        let (result, deferred) = self.gcx.dcx().defer(job);
        self.diagnostics[contract_id].lock().append(deferred);
        result
    }

    fn schedule(&self, contract_id: ContractId) -> Result<ScheduledContract<'gcx>> {
        self.defer_diagnostics(contract_id, || self.schedule_contract(contract_id))
    }

    fn finish(
        &self,
        contract_id: ContractId,
        scheduled: ScheduledContract<'gcx>,
    ) -> Result<ContractArtifact> {
        self.defer_diagnostics(contract_id, || self.finish_contract(contract_id, scheduled))
    }

    /// Lowers, optimizes, and schedules a contract whose embedded bytecode stays deferred.
    fn schedule_contract(&self, contract_id: ContractId) -> Result<ScheduledContract<'gcx>> {
        let Self { gcx, captures, graph, .. } = *self;
        let _span = tracing::debug_span!(
            parent: &self.span,
            "schedule_contract",
            contract = %gcx.contract_fully_qualified_name(contract_id)
        )
        .entered();
        let mut module = lower::lower_contract(gcx, contract_id);
        gcx.dcx().has_errors()?;
        let capture_mir = captures.mir.contains(contract_id);
        let final_mir = dumps_final_mir(gcx);
        let needs_backend = captures.bytecode.contains(contract_id)
            || captures.evm_ir.contains(contract_id)
            || captures.debug_info.contains(contract_id)
            || !graph.dependents[contract_id].is_empty()
            || final_mir;
        let runtime_data =
            captures.runtime_data.filter(|_| needs_backend).map(|data| data(contract_id));
        append_runtime_data(
            &mut module,
            runtime_data.as_ref(),
            crate::link::qualified_name(gcx, contract_id),
        );
        let capture_built =
            capture_mir && !module.is_optimized() && gcx.sess.opts.unstable.mir_pipeline.is_none();
        let built_mir = (capture_built && needs_backend).then(|| module.clone());
        let codegen = if needs_backend {
            module.set_debug_info_tracked(captures.debug_info.contains(contract_id));
            let mut codegen = Box::new(EvmCodegen::new(gcx));
            codegen.set_capture_mir(capture_mir && (!capture_built || final_mir));
            codegen.set_capture_evm_ir(captures.evm_ir.contains(contract_id));
            codegen.set_capture_scheduled_evm_ir(
                captures.evm_ir.contains(contract_id) && dumps_scheduled_evm_ir(gcx),
            );
            codegen.set_capture_debug_info(captures.debug_info.contains(contract_id));
            let scheduled = codegen.schedule_module(&mut module);
            gcx.dcx().has_errors()?;
            scheduled.then_some(codegen)
        } else {
            if capture_mir && !capture_built {
                let _changed = run_pipeline(gcx, &mut module, None);
                gcx.dcx().has_errors()?;
            }
            None
        };
        Ok(ScheduledContract { module, codegen, built_mir })
    }

    /// Supplies the embedded bytecode of a scheduled contract and completes its artifact.
    fn finish_contract(
        &self,
        contract_id: ContractId,
        scheduled: ScheduledContract<'gcx>,
    ) -> Result<ContractArtifact> {
        let Self { gcx, captures, graph, .. } = *self;
        let _span = tracing::debug_span!(
            parent: &self.span,
            "finish_contract",
            contract = %gcx.contract_fully_qualified_name(contract_id)
        )
        .entered();
        let ScheduledContract { module, codegen, built_mir } = scheduled;
        let children = graph.dependencies[contract_id]
            .iter()
            .map(|dependency| {
                let artifact = self.artifacts[dependency]
                    .get()
                    .expect("dependency artifact should have been generated");
                let mut libraries = LibraryTable::default();
                let deployment_relocations =
                    library_relocations(&artifact.deployment_link_references, &mut libraries);
                let runtime_relocations =
                    library_relocations(&artifact.runtime_link_references, &mut libraries);
                let bytecodes = ContractBytecodes {
                    deployment: RelocatableBytecode {
                        bytes: artifact.deployment.clone(),
                        relocations: deployment_relocations,
                        libraries: libraries.clone(),
                        trailers: artifact.deployment_trailers.clone(),
                    },
                    runtime: RelocatableBytecode {
                        bytes: artifact.runtime.clone(),
                        relocations: runtime_relocations,
                        libraries,
                        trailers: artifact.runtime_trailers.clone(),
                    },
                };
                (crate::link::qualified_name(gcx, dependency), bytecodes)
            })
            .collect::<EmbeddedBytecodes>();
        assert_eq!(
            children.len(),
            graph.dependencies[contract_id].count(),
            "embedded contracts must have distinct source-qualified names"
        );
        let artifact = match codegen {
            Some(mut codegen) => {
                let artifact = codegen.finish_module(&module, &children);
                gcx.dcx().has_errors()?;
                artifact
            }
            None => EvmArtifact::default(),
        };
        let capture_mir = captures.mir.contains(contract_id);
        warn_code_size_limits(
            gcx,
            Some(contract_id),
            artifact.deployment.len(),
            artifact.runtime.len(),
        );
        let immutable_references = artifact
            .immutable_references
            .iter()
            .map(|reference| ImmutableReference {
                variable_id: module
                    .immutable(reference.id)
                    .variable_id
                    .map(|id| VariableId::from_usize(id.index())),
                start: reference.code_offset + 1,
                type_size: reference.type_size,
            })
            .collect();
        let deployment_link_references = collect_library_references(
            &artifact.deployment_library_relocations,
            &artifact.libraries,
        );
        let runtime_link_references =
            collect_library_references(&artifact.runtime_library_relocations, &artifact.libraries);
        let final_mir = (capture_mir && dumps_final_mir(gcx)).then(|| {
            let mut snapshot = module.clone();
            snapshot.backend_memory = artifact.backend_memory.clone();
            snapshot
        });
        let mir = capture_mir.then(|| built_mir.unwrap_or(module));

        Ok(ContractArtifact {
            deployment: artifact.deployment.into_boxed_slice().into(),
            runtime: artifact.runtime.into_boxed_slice().into(),
            immutable_references,
            deployment_link_references,
            runtime_link_references,
            deployment_trailers: artifact.deployment_trailers,
            runtime_trailers: artifact.runtime_trailers,
            mir,
            final_mir,
            deployment_evm_ir: artifact.deployment_evm_ir,
            runtime_evm_ir: artifact.runtime_evm_ir,
            runtime_scheduled_evm_ir: artifact.runtime_scheduled_evm_ir,
            deployment_debug_info: artifact.deployment_debug_info,
            runtime_debug_info: artifact.runtime_debug_info,
        })
    }
}

/// Converts named artifact references into identities for embedded bytecode.
fn library_relocations(
    references: &[LibraryReference],
    libraries: &mut LibraryTable,
) -> Vec<LibraryRelocation> {
    references
        .iter()
        .map(|reference| LibraryRelocation {
            offset: reference.start,
            library: libraries.intern(reference.library),
        })
        .collect()
}

/// Resolves the assembler's library relocations to source-qualified names.
fn collect_library_references(
    relocations: &[LibraryRelocation],
    libraries: &LibraryTable,
) -> Vec<LibraryReference> {
    relocations
        .iter()
        .map(|reloc| LibraryReference {
            library: *libraries.get(reloc.library).expect("valid artifact library ID"),
            start: reloc.offset,
        })
        .collect()
}

fn append_runtime_data(module: &mut Module, data: Option<&Bytes>, contract: QualifiedName) {
    if let Some(data) = data.filter(|data| !data.is_empty()) {
        module.append_runtime_data(data.clone(), None, contract);
    }
}

/// Returns whether the session dumps runtime EVM IR as stack scheduling emits it.
fn dumps_scheduled_evm_ir(gcx: Gcx<'_>) -> bool {
    let dump = gcx.sess.opts.unstable.dump.as_ref();
    dump.is_some_and(|dump| dump.kinds.contains(&DumpKind::EvmIrRuntimeScheduled))
}

/// Warns, with solc's codes, when bytecode exceeds the size limits of the target EVM version:
/// EIP-170's on deployed code and EIP-3860's on initcode. `contract` is the Solidity contract the
/// bytecode compiles, if any; the warnings then point at it and suggest how to shrink it.
pub(crate) fn warn_code_size_limits(
    gcx: Gcx<'_>,
    contract: Option<ContractId>,
    deployment: usize,
    runtime: usize,
) {
    const HELP: &str = "consider enabling the optimizer with a low runs value, turning off revert strings, or using libraries";
    let evm_version = gcx.sess.opts.evm_version;
    let amsterdam = evm_version >= EvmVersion::Amsterdam;
    let span = contract.map(|id| gcx.hir.contract(id).span);
    if let Some(limit) = evm_version.runtime_code_size_limit()
        && runtime > limit
    {
        let fork = if amsterdam { EvmVersion::Amsterdam } else { EvmVersion::SpuriousDragon };
        let mut diag = gcx
            .dcx()
            .warn(format!("contract code size is {runtime} bytes and exceeds {limit} bytes"))
            .code(error_code!(5574))
            .note(format!("the limit was introduced in {fork}"))
            .note("this contract may not be deployable on Mainnet");
        if let Some(span) = span {
            diag = diag.span(span).help(HELP);
        }
        diag.emit();
    }
    if let Some(limit) = evm_version.initcode_size_limit()
        && deployment > limit
    {
        let fork = if amsterdam { EvmVersion::Amsterdam } else { EvmVersion::Shanghai };
        let mut diag = gcx
            .dcx()
            .warn(format!("contract initcode size is {deployment} bytes and exceeds {limit} bytes"))
            .code(error_code!(3860))
            .note(format!("the limit was introduced in {fork}"))
            .note("this contract may not be deployable on Mainnet");
        if let Some(span) = span {
            diag = diag.span(span).help(HELP);
        }
        diag.emit();
    }
}

/// Returns whether `-Zdump=mir-final` asks for the MIR the backend compiles.
fn dumps_final_mir(gcx: Gcx<'_>) -> bool {
    gcx.sess
        .opts
        .unstable
        .dump
        .as_ref()
        .is_some_and(|dump| dump.kinds.contains(&DumpKind::MirFinal))
}
